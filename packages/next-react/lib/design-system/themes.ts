// Helper function to apply theme
export function applyTheme(themeName: string): string {
  const theme = themes[themeName]
  if (!theme) return ''
  
  return Object.entries(theme)
    .filter(([key]) => key !== 'name' && key !== 'category')
    .map(([_, value]) => value)
    .join(' ')
}

// Get themes by category
export function getThemesByCategory(category: ThemeConfig['category']): Record<string, ThemeConfig> {
  return Object.fromEntries(
    Object.entries(themes).filter(([_, theme]) => theme.category === category)
  )
}

// Generate additional themes dynamically
export function generateDynamicTheme(
  baseColor: string,
  intensity: 'light' | 'medium' | 'heavy' = 'medium'
): ThemeConfig {
  const opacities = {
    light: { bg: '10', card: '20', primary: '25', overlay: '50' },
    medium: { bg: '15', card: '30', primary: '35', overlay: '60' },
    heavy: { bg: '20', card: '40', primary: '45', overlay: '70' },
  }
  
  const op = opacities[intensity]
  
  return {
    name: `Dynamic ${baseColor} ${intensity}`,
    category: 'glass',
    background: `bg-${baseColor}-500/${op.bg}`,
    foreground: `text-${baseColor}-50`,
    card: `bg-${baseColor}-500/${op.card} backdrop-blur-xl`,
    blur: 'backdrop-blur-xl',
    border: `border-${baseColor}-400/30`,
    primary: `bg-${baseColor}-600/${op.primary}`,
    secondary: `bg-${baseColor}-500/${op.primary}`,
    accent: `bg-${baseColor}-700/${op.primary}`,
    destructive: 'bg-red-600/35',
    muted: `bg-${baseColor}-400/15`,
    overlay: `bg-${baseColor}-900/${op.overlay} backdrop-blur-md`,
    shadow: `shadow-2xl shadow-${baseColor}-900/30`,
  }
}

